// Capturas em celular Android (emulação Pixel 7) a partir do build web.
// Uso: node scripts/screenshots-mobile.mjs [url] [pasta]
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium, devices } = require('playwright');

const URL = process.argv[2] || 'http://localhost:4173';
const OUT = process.argv[3] || 'docs/screenshots/android';
const PASS = 'SenhaForte#2026';

const b = await chromium.launch();
const ctx = await b.newContext({ ...devices['Pixel 7'], locale: 'pt-BR' });
const p = await ctx.newPage();
const errors = [];
p.on('pageerror', (e) => errors.push(e.message));
const shot = async (name) => {
  await p.waitForTimeout(700);
  await p.screenshot({ path: `${OUT}/${name}.png` });
  console.log('✓', name);
};
const menu = async () => {
  await p.click('.mnav-item:has-text("Menu")');
  await p.waitForTimeout(400);
};
const openPage = async (title) => {
  await menu();
  await p.click(`.sidebar .tree-title:text-is("${title}")`);
  await p.waitForTimeout(900);
};

await p.goto(URL);
await p.waitForSelector('.wizard');
await shot('01-assistente');
await p.click('text=Avançar');
await p.click('text=Avançar');
const pw = await p.$$('input[type=password]');
await pw[0].fill(PASS);
await pw[1].fill(PASS);
await p.click('text=Criar cofre');
await p.waitForSelector('.recovery-code', { timeout: 30000 });
await p.click('.check.big input');
await p.click('text=Avançar');
for (const t of ['Plano de projeto', 'Lista de leitura']) await p.click(`.starter:has-text("${t}")`);
await shot('02-templates-iniciais');
await p.click('text=Começar a usar');
await p.waitForSelector('.home', { timeout: 20000 });
await shot('03-inicio');
await p.click('.mnav-fab');
await shot('04-criar');
await p.click('.sheet-back', { position: { x: 20, y: 40 } });
await menu();
await shot('05-menu');
await p.click('.sidebar .tree-title:text-is("Comece por aqui")');
await p.waitForTimeout(900);
await shot('06-editor');
await p.click('.ProseMirror');
await p.keyboard.press('Control+End');
await p.keyboard.press('Enter');
await p.keyboard.press('Enter');
await p.keyboard.type('/');
await p.waitForSelector('.suggest');
await shot('07-comandos');
await p.keyboard.press('Escape');
await openPage('Painel de projetos');
await p.$eval('.content', (e) => e.scrollTo(0, 280));
await shot('08-relatorio');
await menu();
await p.click('.sidebar .tree-item:has-text("Painel de projetos") .tree-caret');
await p.click('.sidebar .tree-title:text-is("Tarefas")');
await p.waitForTimeout(900);
await shot('09-kanban');
await openPage('Cofre de senhas');
await shot('10-senhas');
await openPage('Segundo cérebro');
await p.click('.mode-seg button >> nth=1');
await p.waitForSelector('.canvas-area');
await p.waitForTimeout(600);
const box = await (await p.$('.canvas-area')).boundingBox();
await p.click('.dock-btn[title^="Nota"]');
await p.mouse.click(box.x + box.width * 0.7, box.y + 120);
await p.keyboard.type('Ideia: festival de verão');
await p.click('.dock-btn[title^="Caneta"]');
await p.mouse.move(box.x + 60, box.y + 460);
await p.mouse.down();
for (let i = 0; i <= 24; i++) await p.mouse.move(box.x + 60 + i * 11, box.y + 460 + Math.sin(i / 2.5) * 26);
await p.mouse.up();
await p.click('.dock-btn[title^="Selecionar"]');
await shot('11-quadro');
await p.click('.mode-seg button >> nth=0');
await p.click('.mnav-item:has-text("IA")');
await shot('12-ia');
await p.click('.ai-head .icon-btn');
await menu();
await p.click('.sidebar >> text="Grafo de ideias"');
await p.waitForTimeout(2500);
await shot('13-grafo');
await menu();
await p.click('.sidebar >> text="Configurações"');
await shot('14-configuracoes');
await menu();
await p.click('.sidebar >> text="Apoie o projeto"');
await shot('15-apoie');
await menu();
await p.click('.side-foot .icon-btn');
await p.waitForSelector('.auth-card');
await shot('16-login');
console.log(errors.length ? 'ERROS:\n' + errors.join('\n') : 'sem erros de página');
await b.close();
